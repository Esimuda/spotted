function attachSource(species: Omit<Species, "sourceUrl">): Species {
  return {
    ...species,
    sourceUrl: `https://en.wikipedia.org/wiki/${species.scientificName.replace(/ /g, "_")}`,
  };
}

export const SPECIES: Species[] = [...CATALOG.map(attachSource), ...MORE_SPECIES];

const BY_ID = new Map(SPECIES.map((species) => [species.id, species]));

export function speciesById(id: string): Species | undefined {
  return BY_ID.get(id);
}

export function speciesIsSensitive(species: Species): boolean {
  return species.sensitive || species.status === "VU" || species.status === "EN" || species.status === "CR";
}

export function speciesPrompt(species: Species): string {
  const kind =
    species.group === "plant" ? "plant" : species.group === "insect" ? "insect" : species.group;
  return `a photo of a ${species.commonName}, ${species.scientificName}, a ${kind}`;
}

export function speciesInGroup(group: SpeciesGroup | "all"): Species[] {
  if (group === "all") return SPECIES;
  return SPECIES.filter((species) => species.group === group);
}
